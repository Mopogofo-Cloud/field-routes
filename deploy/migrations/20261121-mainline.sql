BEGIN;
SET LOCAL ROLE fieldroutes_owner;
SET LOCAL search_path TO fieldroutes;

CREATE TABLE IF NOT EXISTS mainline_projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, location TEXT NOT NULL DEFAULT '', supervisor TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL CHECK (state IN ('Not Started','In Progress','Completed')),
  lunch_provided INTEGER NOT NULL DEFAULT 0 CHECK (lunch_provided IN (0,1)),
  estimated_hundredths bigint CHECK (estimated_hundredths>=0), driver_cents bigint CHECK (driver_cents>=0),
  price_ten_thousandths bigint CHECK (price_ten_thousandths>=0), due_date TEXT,
  revision bigint NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS mainline_dailies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id bigint NOT NULL REFERENCES mainline_projects(id), date TEXT NOT NULL,
  footage_hundredths bigint NOT NULL DEFAULT 0 CHECK (footage_hundredths>=0),
  expenses TEXT NOT NULL DEFAULT '[]', priority TEXT CHECK (priority IN ('HIGH','MEDIUM','LOW')),
  comments TEXT NOT NULL DEFAULT '', revision bigint NOT NULL DEFAULT 0);

CREATE INDEX IF NOT EXISTS mainline_dailies_by_project ON mainline_dailies(project_id,date,id);

CREATE INDEX IF NOT EXISTS mainline_dailies_by_date ON mainline_dailies(date,id);

CREATE TABLE IF NOT EXISTS mainline_daily_members (
  daily_id bigint NOT NULL REFERENCES mainline_dailies(id) ON DELETE CASCADE,
  person_id bigint NOT NULL REFERENCES people(id), name TEXT NOT NULL,
  is_driver INTEGER NOT NULL DEFAULT 0 CHECK (is_driver IN (0,1)), PRIMARY KEY(daily_id,person_id));

CREATE INDEX IF NOT EXISTS mainline_member_dailies ON mainline_daily_members(person_id,daily_id);

CREATE TABLE IF NOT EXISTS mainline_daily_vehicles (
  daily_id bigint NOT NULL REFERENCES mainline_dailies(id) ON DELETE CASCADE,
  vehicle_id bigint NOT NULL REFERENCES vehicles(id), name TEXT NOT NULL, brand TEXT NOT NULL, plate TEXT NOT NULL,
  PRIMARY KEY(daily_id,vehicle_id));

CREATE INDEX IF NOT EXISTS mainline_vehicle_dailies ON mainline_daily_vehicles(vehicle_id,daily_id);

CREATE TABLE IF NOT EXISTS mainline_media (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, daily_id bigint NOT NULL REFERENCES mainline_dailies(id) ON DELETE CASCADE,
  category TEXT NOT NULL CHECK(category IN ('map','pictures','receipts')),
  mime TEXT NOT NULL CHECK(mime IN ('image/jpeg','image/png','image/webp')),
  byte_count INTEGER NOT NULL CHECK(byte_count BETWEEN 1 AND 12582912),
  content bytea, destination TEXT, object_key TEXT, sha256 TEXT,
  UNIQUE(destination,object_key),
  CHECK ((content IS NOT NULL AND length(content)=byte_count AND destination IS NULL AND object_key IS NULL AND sha256 IS NULL)
     OR (content IS NULL AND destination IS NOT NULL AND object_key IS NOT NULL AND sha256 IS NOT NULL)));

CREATE INDEX IF NOT EXISTS mainline_media_daily ON mainline_media(daily_id,category,id);

CREATE OR REPLACE FUNCTION collect_removed_mainline_media() RETURNS trigger
    LANGUAGE plpgsql SET search_path=pg_catalog AS $$
    BEGIN
        INSERT INTO fieldroutes.photo_cleanup(destination,object_key,eligible_at)
        VALUES(OLD.destination,OLD.object_key,floor(extract(epoch FROM clock_timestamp()))::bigint)
        ON CONFLICT(destination,object_key) DO UPDATE SET eligible_at=excluded.eligible_at,committable=0;
        RETURN OLD;
    END
    $$;

CREATE OR REPLACE TRIGGER collect_removed_mainline_media AFTER DELETE ON mainline_media
    FOR EACH ROW WHEN (OLD.object_key IS NOT NULL) EXECUTE FUNCTION collect_removed_mainline_media();

CREATE TABLE IF NOT EXISTS mainline_project_documents (
    project_id BIGINT NOT NULL REFERENCES mainline_projects(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK(kind IN ('redline','fiber','locates')),
    revision BIGINT NOT NULL CHECK(revision > 0), updated_at TEXT NOT NULL,
    byte_count INTEGER NOT NULL CHECK(byte_count BETWEEN 1 AND 12582912),
    sha256 TEXT NOT NULL, content BYTEA, destination TEXT, object_key TEXT,
    PRIMARY KEY(project_id,kind), UNIQUE(destination,object_key),
    CHECK((content IS NOT NULL AND length(content)=byte_count AND destination IS NULL AND object_key IS NULL)
       OR (content IS NULL AND destination IS NOT NULL AND object_key IS NOT NULL)));

CREATE OR REPLACE FUNCTION fieldroutes.collect_mainline_document() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    IF OLD.object_key IS NOT NULL AND (TG_OP='DELETE' OR OLD.object_key IS DISTINCT FROM NEW.object_key
                                       OR OLD.destination IS DISTINCT FROM NEW.destination) THEN
        INSERT INTO fieldroutes.photo_cleanup(destination,object_key,eligible_at,committable)
        VALUES(OLD.destination,OLD.object_key,floor(extract(epoch FROM clock_timestamp()))::bigint,0)
        ON CONFLICT(destination,object_key) DO UPDATE SET eligible_at=excluded.eligible_at,committable=0;
    END IF;
    RETURN NULL;
END
$$;

CREATE OR REPLACE TRIGGER collect_mainline_document AFTER DELETE OR UPDATE OF object_key,destination
ON mainline_project_documents FOR EACH ROW EXECUTE FUNCTION fieldroutes.collect_mainline_document();

GRANT SELECT, INSERT, UPDATE, DELETE ON mainline_projects, mainline_dailies, mainline_daily_members, mainline_daily_vehicles, mainline_media, mainline_project_documents TO fieldroutes_app;
GRANT USAGE ON SEQUENCE mainline_projects_id_seq, mainline_dailies_id_seq, mainline_media_id_seq TO fieldroutes_app;
COMMIT;
