final class MainlineMedia {
    private MainlineMedia() {}

    private static final List<String> GALLERIES = List.of("map", "pictures", "receipts");
    private static final int BATCH_SIZE = 10;
    private static final String IMAGE_TYPES = "image/jpeg,image/png,image/webp";
    private static final Pattern PAGE = Pattern.compile("/mainline/dailies/([0-9]+)/photos");
    private static final Pattern URL = Pattern.compile("/mainline/dailies/([0-9]+)/media/(map|pictures|receipts|[0-9]+)(/remove)?");

    static List<String> schema(boolean pg) {
        String table = """
            CREATE TABLE IF NOT EXISTS mainline_media (
              id %s, daily_id %s NOT NULL REFERENCES mainline_dailies(id) ON DELETE CASCADE,
              category TEXT NOT NULL CHECK(category IN ('map','pictures','receipts')),
              mime TEXT NOT NULL CHECK(mime IN ('image/jpeg','image/png','image/webp')),
              byte_count INTEGER NOT NULL CHECK(byte_count BETWEEN 1 AND 12582912),
              content %s, destination TEXT, object_key TEXT, sha256 TEXT,
              UNIQUE(destination,object_key),
              CHECK ((content IS NOT NULL AND length(content)=byte_count AND destination IS NULL AND object_key IS NULL AND sha256 IS NULL)
                 OR (content IS NULL AND destination IS NOT NULL AND object_key IS NOT NULL AND sha256 IS NOT NULL)))
            """.formatted(pg ? "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT",
                          pg ? "bigint" : "INTEGER", pg ? "bytea" : "BLOB");
        String index = "CREATE INDEX IF NOT EXISTS mainline_media_daily ON mainline_media(daily_id,category,id)";
        if (pg) return List.of(table, index, """
            CREATE OR REPLACE FUNCTION collect_removed_mainline_media() RETURNS trigger
                LANGUAGE plpgsql SET search_path=pg_catalog AS $$
                BEGIN
                    INSERT INTO fieldroutes.photo_cleanup(destination,object_key,eligible_at)
                    VALUES(OLD.destination,OLD.object_key,floor(extract(epoch FROM clock_timestamp()))::bigint)
                    ON CONFLICT(destination,object_key) DO UPDATE SET eligible_at=excluded.eligible_at,committable=0;
                    RETURN OLD;
                END
                $$
            """, """
            CREATE OR REPLACE TRIGGER collect_removed_mainline_media AFTER DELETE ON mainline_media
                FOR EACH ROW WHEN (OLD.object_key IS NOT NULL) EXECUTE FUNCTION collect_removed_mainline_media()
            """);
        return List.of(table, index, """
            CREATE TRIGGER IF NOT EXISTS collect_removed_mainline_media AFTER DELETE ON mainline_media
            WHEN OLD.object_key IS NOT NULL
            BEGIN
                INSERT INTO photo_cleanup(destination,object_key,eligible_at) VALUES(OLD.destination,OLD.object_key,unixepoch())
                ON CONFLICT(destination,object_key) DO UPDATE SET eligible_at=excluded.eligible_at,committable=0;
            END
            """);
    }

    static ArrayNode list(Connection db, ObjectNode user, long daily) throws Exception {
        return transaction(db, false, () -> {
            Mainline.requireDaily(db, user, daily);
            return rows(db, "SELECT id,category,mime,byte_count FROM mainline_media WHERE daily_id=? ORDER BY id", daily);
        });
    }

    private static void checkBatch(Connection db, ObjectNode user, long daily, String category, long latest) throws Exception {
        Mainline.requireDaily(db, user, daily);
        var last = one(db, "SELECT coalesce(max(id),0) AS latest FROM mainline_media WHERE daily_id=? AND category=?", daily, category);
        if (latest != last.get("latest").asLong()) throw new Problem(409, "The gallery changed. Reload the photos page before uploading.");
    }

    static void add(Connection db, ObjectNode user, long daily, String category, long latest,
                    List<Part> files, S3Photos store) throws Exception {
        if (!GALLERIES.contains(category)) throw new Problem(404, "Gallery not found.");
        if (files.isEmpty() || files.size() > BATCH_SIZE) throw new Problem(422, "Choose 1 to 10 photos per upload.");
        for (Part file : files) {
            if (file.getSize() < 1 || file.getSize() > S3Photos.MAX_BYTES)
                throw new Problem(422, "Each photo must be between 1 byte and 12 MiB.");
        }
        checkBatch(db, user, daily, category, latest);
        List<PhotoStorage.Upload> uploads = store == null ? List.of() : PhotoStorage.stage(db, store, files);
        transaction(db, true, () -> {
            checkBatch(db, user, daily, category, latest);
            if (store == null) {
                for (Part file : files) {
                    try (var input = new BufferedInputStream(file.getInputStream())) {
                        input.mark(16);
                        String mime = Store.mime(input.readNBytes(12));
                        input.reset();
                        try (var stmt = db.prepareStatement("INSERT INTO mainline_media(daily_id,category,mime,byte_count,content) VALUES(?,?,?,?,?)")) {
                            bind(stmt, daily, category, mime, file.getSize());
                            stmt.setBinaryStream(5, input, Math.toIntExact(file.getSize()));
                            stmt.executeUpdate();
                        }
                    }
                }
            } else {
                for (var upload : uploads) {
                    PhotoStorage.claimUpload(db, store, upload.key());
                    change(db, """
                        INSERT INTO mainline_media(daily_id,category,mime,byte_count,destination,object_key,sha256)
                        VALUES(?,?,?,?,?,?,?)
                        """, daily, category, upload.mime(), upload.part().getSize(), store.destination, upload.key(), upload.hash());
                }
            }
            return null;
        });
    }

    private record Image(String mime, byte[] bytes, String destination, String key, int size, String hash) {}

    static Store.Photo photo(Connection db, ObjectNode user, long daily, long id) throws Exception {
        return photo(db, user, daily, id, PhotoStorage::active);
    }

    static Store.Photo photo(Connection db, ObjectNode user, long daily, long id, Supplier<S3Photos> storage) throws Exception {
        Image image = transaction(db, false, () -> {
            Mainline.requireDaily(db, user, daily);
            try (var stmt = db.prepareStatement("SELECT mime,content,destination,object_key,byte_count,sha256 FROM mainline_media WHERE daily_id=? AND id=?")) {
                bind(stmt, daily, id);
                try (var rs = stmt.executeQuery()) {
                    if (!rs.next()) throw new Problem(404, "Photo not found.");
                    return new Image(rs.getString(1),rs.getBytes(2),rs.getString(3),rs.getString(4),rs.getInt(5),rs.getString(6));
                }
            }
        });
        if (image.bytes() != null) return new Store.Photo(image.mime(),image.bytes());
        var store = storage.get();
        if (store == null || !store.destination.equals(image.destination())) throw S3Photos.unavailable();
        return new Store.Photo(image.mime(), store.get(image.key(),image.size(),image.hash()));
    }

    static String remove(Connection db, ObjectNode user, long daily, long id) throws Exception {
        return transaction(db, true, () -> {
            Mainline.requireDaily(db, user, daily);
            var image = one(db, "SELECT category FROM mainline_media WHERE daily_id=? AND id=?", daily,id);
            if (image == null) throw new Problem(404, "Photo not found.");
            change(db, "DELETE FROM mainline_media WHERE daily_id=? AND id=?", daily,id);
            return image.get("category").asText();
        });
    }

    static boolean handle(HttpServletRequest req, HttpServletResponse res, Connection db, ObjectNode user) throws Exception {
        var pagePath = PAGE.matcher(req.getRequestURI());
        if (pagePath.matches()) {
            if (!Set.of("GET","HEAD").contains(req.getMethod())) throw new Problem(405, "Method not allowed.");
            photoPage(res,db,user,id(pagePath.group(1)));
            return true;
        }
        var match = URL.matcher(req.getRequestURI());
        if (!match.matches()) return false;
        long daily = id(match.group(1));
        String part = match.group(2);
        boolean post = req.getMethod().equals("POST");
        String galleryPath = "/mainline/dailies/" + daily + "/photos";
        if (GALLERIES.contains(part)) {
            if (!post || match.group(3) != null) throw new Problem(405, "Method not allowed.");
            Mainline.requireDaily(db, user, daily);
            List<Part> files = new ArrayList<>();
            String latest = null;
            try {
                for (var attachment : req.getParts()) {
                    if ("latest".equals(attachment.getName()) && attachment.getSubmittedFileName() == null && latest == null && attachment.getSize() <= 19) {
                        try (var in = attachment.getInputStream()) {
                            latest = new String(in.readAllBytes(), java.nio.charset.StandardCharsets.US_ASCII);
                        }
                    } else if ("photos".equals(attachment.getName()) && attachment.getSubmittedFileName() != null) {
                        if (!attachment.getSubmittedFileName().isEmpty()) files.add(attachment);
                    } else throw new Problem(422, "Unexpected gallery field.");
                }
            } catch (ServletException ex) { throw new Problem(422, "Choose photos using the gallery upload form."); }
            if (latest == null || !latest.matches("[0-9]{1,19}")) throw new Problem(422, "Invalid gallery version.");
            add(db,user,daily,part,id(latest),files,PhotoStorage.active());
            redirect(res,galleryPath + "#media-" + part);
        } else if (match.group(3) != null) {
            if (!post) throw new Problem(405, "Method not allowed.");
            String category = remove(db,user,daily,id(part));
            redirect(res,galleryPath + "#media-" + category);
        } else {
            if (!Set.of("GET","HEAD").contains(req.getMethod())) throw new Problem(405, "Method not allowed.");
            App.sendPhoto(res, () -> photo(db,user,daily,id(part)));
        }
        return true;
    }

    static String renderSummary(Connection db, ObjectNode user, long daily) throws Exception {
        String galleryPath = "/mainline/dailies/" + daily + "/photos";
        return "<section class='panel stack'><h2>Daily photos</h2>" + galleries(list(db,user,daily), daily, false)
            + "<a class='btn secondary' href='" + galleryPath + "' target='_blank' rel='noopener'>Manage photos (opens in a new tab)</a></section>";
    }

    private static void photoPage(HttpServletResponse res, Connection db, ObjectNode user, long daily) throws Exception {
        var report = Mainline.daily(db,user,daily);
        String path = "/mainline/dailies/" + daily;
        String title = "Daily photos";
        String body = "<div class='stack'>" + link("← Daily report",path,"worker-back worker-text-button")
            + "<header><h1>Daily photos</h1><p>" + h(value(report,"project_name")) + " · " + h(value(report,"date")) + "</p></header>"
            + "<section class='panel stack'><p class='helper'>Upload up to 10 images at a time. You can add more in another batch. JPEG, PNG or WebP, up to 12 MiB each.</p>"
            + galleries(list(db,user,daily),daily,true) + "</section></div>";
        page(res,user,title,body);
    }

    private static String galleries(ArrayNode gallery, long daily, boolean edit) {
        String root = "/mainline/dailies/" + daily + "/media/";
        String heading = edit ? "h2" : "h3";
        var out = new StringBuilder();
        for (String category : GALLERIES) {
            int count = 0;
            long latest = 0;
            var images = new StringBuilder();
            for (JsonNode image : gallery) {
                if (!image.get("category").asText().equals(category)) continue;
                long id = image.get("id").asLong();
                latest = id;
                count++;
                if (!edit && count > 3) continue;
                String url = root + id;
                images.append("<div><a href='").append(url).append("'");
                if (!edit) images.append(" target='_blank' rel='noopener'");
                images.append("><img loading='lazy' width='96' height='72' alt='").append(label(category)).append(" image ").append(count)
                    .append(edit ? "" : " (opens in a new tab)").append("' src='").append(url).append("'></a>");
                if (edit) images.append("<form method='post' action='").append(url)
                    .append("/remove'><button class='secondary'>Remove image ").append(count).append("</button></form>");
                images.append("</div>");
            }
            out.append("<section class='stack' id='media-").append(category).append("'><").append(heading)
                .append(">").append(label(category)).append(" (").append(count).append(")</").append(heading).append(">");
            if (!images.isEmpty()) out.append("<div class='worker-photos'>").append(images).append("</div>");
            if (edit) out.append("<form class='stack' method='post' action='")
                .append(root).append(category).append("' enctype='multipart/form-data'>").append(hidden("latest",Long.toString(latest)))
                .append("<label>Choose images<input type='file' aria-label='Choose images for ").append(label(category))
                .append("' required multiple accept='").append(IMAGE_TYPES)
                .append("' name='photos'></label><button>Upload</button></form>");
            out.append("</section>");
        }
        return out.toString();
    }

    private static String label(String category) {
        return switch (category) { case "map" -> "Map"; case "pictures" -> "Pictures"; default -> "Receipts"; };
    }
}
