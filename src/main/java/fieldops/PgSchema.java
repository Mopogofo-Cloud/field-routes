package fieldops;

import java.sql.Connection;
import java.sql.SQLException;

final class PgSchema {
    static final String NAME = "fieldroutes";

    private PgSchema() {}

    /** Creates an empty schema inside the caller's transaction. The importer supplies the original IDs. */
    static void createTables(Connection db) throws SQLException {
        try (var sql = db.createStatement()) {
            sql.execute("CREATE SCHEMA IF NOT EXISTS fieldroutes");
            sql.execute("SET LOCAL search_path TO fieldroutes");
            sql.execute("REVOKE ALL ON SCHEMA fieldroutes FROM PUBLIC");
            sql.execute("""
                DO $$
                BEGIN
                    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
                        REVOKE ALL ON SCHEMA fieldroutes FROM anon;
                    END IF;
                    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
                        REVOKE ALL ON SCHEMA fieldroutes FROM authenticated;
                    END IF;
                END
                $$
                """);

            // C collation keeps text ordering and ASCII-only case folding consistent with SQLite.
            // Keep serialized JSON, decimal rates and historical timestamps in their original representations.
            sql.execute("""
                CREATE TABLE people (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username text COLLATE "C" NOT NULL, password_hash text COLLATE "C" NOT NULL,
                    name text COLLATE "C" NOT NULL, is_admin integer NOT NULL DEFAULT 0,
                    must_change_password integer NOT NULL DEFAULT 0, role text COLLATE "C" NOT NULL DEFAULT '',
                    pay_basis text COLLATE "C" CHECK(pay_basis IN ('daily','production')), rate_cents bigint,
                    email text COLLATE "C", phone text COLLATE "C", address text COLLATE "C",
                    start_date text COLLATE "C", status text COLLATE "C", wgidig_employee_id text COLLATE "C",
                    wgidig_account_type text COLLATE "C", wgidig_availability text COLLATE "C"
                );
                CREATE UNIQUE INDEX people_username ON people(lower(username));
                CREATE UNIQUE INDEX people_wgidig_id ON people(wgidig_employee_id);
                CREATE TABLE sessions (
                    token_hash text COLLATE "C" PRIMARY KEY, person_id bigint NOT NULL REFERENCES people,
                    expires bigint NOT NULL
                );
                CREATE INDEX session_expiry ON sessions(expires);
                CREATE TABLE login_attempts (
                    source text COLLATE "C" PRIMARY KEY, started bigint NOT NULL, count bigint NOT NULL
                );
                CREATE TABLE roles (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text COLLATE "C" NOT NULL
                );
                CREATE UNIQUE INDEX roles_name ON roles(lower(name));
                CREATE TABLE report_items (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text COLLATE "C" NOT NULL,
                    unit text COLLATE "C" NOT NULL DEFAULT ''
                );
                CREATE UNIQUE INDEX report_items_name_unit ON report_items(lower(name),lower(unit));
                CREATE TABLE entities (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text COLLATE "C" NOT NULL
                );
                CREATE UNIQUE INDEX entities_name ON entities(lower(name));
                CREATE TABLE wgidig_entities (
                    entity_id bigint PRIMARY KEY REFERENCES entities, wgidig_id bigint NOT NULL UNIQUE
                );
                CREATE TABLE wgidig_roster_import (
                    singleton integer PRIMARY KEY CHECK(singleton=1), source_sha256 text COLLATE "C" NOT NULL,
                    people_count bigint NOT NULL, roles_count bigint NOT NULL
                );
                CREATE TABLE wgidig_roster_links (
                    source_id text COLLATE "C" PRIMARY KEY, person_id bigint NOT NULL UNIQUE REFERENCES people,
                    initial_profile_sha256 text COLLATE "C" NOT NULL
                );
                """);
            sql.execute("""
                CREATE TABLE teams (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text COLLATE "C" NOT NULL,
                    entity_id bigint NOT NULL REFERENCES entities
                );
                CREATE UNIQUE INDEX teams_name ON teams(lower(name));
                CREATE TABLE team_members (
                    team_id bigint NOT NULL REFERENCES teams, person_id bigint NOT NULL REFERENCES people,
                    PRIMARY KEY(team_id,person_id)
                );
                CREATE TABLE routes (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text COLLATE "C" NOT NULL,
                    team_id bigint NOT NULL REFERENCES teams, team_name text COLLATE "C" NOT NULL,
                    entity_id bigint NOT NULL REFERENCES entities, entity_name text COLLATE "C" NOT NULL,
                    address_hash text COLLATE "C" NOT NULL, revision bigint NOT NULL DEFAULT 0,
                    UNIQUE(date,team_id,address_hash)
                );
                CREATE TABLE assignments (
                    route_id bigint NOT NULL REFERENCES routes, person_id bigint NOT NULL REFERENCES people,
                    name text COLLATE "C" NOT NULL, role text COLLATE "C" NOT NULL,
                    pay_basis text COLLATE "C" NOT NULL, rate_cents bigint, PRIMARY KEY(route_id,person_id)
                );
                CREATE INDEX person_routes ON assignments(person_id,route_id);
                CREATE TABLE vehicles (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text COLLATE "C" NOT NULL,
                    brand text COLLATE "C" NOT NULL DEFAULT '', plate text COLLATE "C" NOT NULL DEFAULT ''
                );
                CREATE UNIQUE INDEX vehicles_name ON vehicles(lower(name));
                CREATE TABLE route_vehicles (
                    route_id bigint NOT NULL REFERENCES routes, vehicle_id bigint NOT NULL REFERENCES vehicles,
                    name text COLLATE "C" NOT NULL, brand text COLLATE "C" NOT NULL, plate text COLLATE "C" NOT NULL,
                    PRIMARY KEY(route_id,vehicle_id)
                );
                CREATE INDEX route_vehicle_use ON route_vehicles(vehicle_id,route_id);
                CREATE TABLE jobs (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, route_id bigint NOT NULL REFERENCES routes,
                    position bigint NOT NULL, address text COLLATE "C" NOT NULL, feet_buried double precision,
                    fiber_type text COLLATE "C", bores text COLLATE "C" NOT NULL DEFAULT '[]', submitted_by bigint REFERENCES people,
                    submitted_at text COLLATE "C", revision bigint NOT NULL DEFAULT 0, last_edited_by bigint REFERENCES people,
                    last_edited_at text COLLATE "C", stop_label text COLLATE "C" NOT NULL DEFAULT '' CHECK(stop_label IN ('','drop','damage','survey')),
                    urgent integer NOT NULL DEFAULT 0 CHECK(urgent IN (0,1)), tech_needed integer CHECK(tech_needed IN (0,1)),
                    external_job_id text COLLATE "C" NOT NULL DEFAULT '', conduits text COLLATE "C" NOT NULL DEFAULT '[]',
                    items text COLLATE "C" NOT NULL DEFAULT '[]', comments text COLLATE "C" NOT NULL DEFAULT '',
                    outcome text COLLATE "C" CHECK(outcome IN ('done','pending','cancel')), outcome_reason text COLLATE "C",
                    UNIQUE(route_id,position)
                );
                CREATE TABLE job_removals (
                    job_id bigint PRIMARY KEY REFERENCES jobs, position bigint NOT NULL, removed_at text COLLATE "C" NOT NULL
                );
                CREATE VIEW active_route_jobs AS SELECT j.* FROM jobs j
                    WHERE NOT EXISTS(SELECT 1 FROM job_removals x WHERE x.job_id=j.id);
                CREATE TABLE job_notes (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id bigint NOT NULL REFERENCES jobs,
                    author_id bigint NOT NULL REFERENCES people, author_name text COLLATE "C" NOT NULL,
                    text text COLLATE "C" NOT NULL, created_at text COLLATE "C" NOT NULL
                );
                CREATE INDEX job_notes_by_job ON job_notes(job_id,id);
                """);
            sql.execute("""
                CREATE TABLE photos (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id bigint NOT NULL REFERENCES jobs,
                    mime text COLLATE "C" NOT NULL, content bytea NOT NULL
                );
                CREATE INDEX photos_job ON photos(job_id);
                CREATE TABLE photo_objects (
                    photo_id bigint PRIMARY KEY REFERENCES photos(id) ON DELETE CASCADE,
                    destination text COLLATE "C" NOT NULL, object_key text COLLATE "C" NOT NULL,
                    byte_count bigint NOT NULL CHECK(byte_count BETWEEN 1 AND 12582912), sha256 text COLLATE "C" NOT NULL,
                    UNIQUE(destination,object_key)
                );
                CREATE TABLE photo_cleanup (
                    destination text COLLATE "C" NOT NULL, object_key text COLLATE "C" NOT NULL, eligible_at bigint NOT NULL,
                    committable integer NOT NULL DEFAULT 0, PRIMARY KEY(destination,object_key)
                );
                CREATE INDEX photo_cleanup_due ON photo_cleanup(destination,eligible_at);
                CREATE FUNCTION collect_removed_photo() RETURNS trigger
                    LANGUAGE plpgsql SET search_path=pg_catalog AS $$
                    BEGIN
                        INSERT INTO fieldroutes.photo_cleanup(destination,object_key,eligible_at)
                        VALUES(OLD.destination,OLD.object_key,floor(extract(epoch FROM clock_timestamp()))::bigint)
                        ON CONFLICT(destination,object_key) DO UPDATE SET eligible_at=excluded.eligible_at,committable=0;
                        RETURN OLD;
                    END
                    $$;
                CREATE TRIGGER collect_removed_photo AFTER DELETE ON photo_objects
                    FOR EACH ROW EXECUTE FUNCTION collect_removed_photo();
                """);
            sql.execute("""
                CREATE TABLE payroll_statements (
                    pay_date text COLLATE "C" NOT NULL, person_id bigint NOT NULL REFERENCES people,
                    generated_at text COLLATE "C" NOT NULL, payload text COLLATE "C" NOT NULL, mailing_address text COLLATE "C" NOT NULL,
                    check_number bigint UNIQUE CHECK(check_number BETWEEN 1 AND 999999999), PRIMARY KEY(pay_date,person_id)
                );
                CREATE TABLE payroll_schedule (id integer PRIMARY KEY CHECK(id=1), last_friday text COLLATE "C" NOT NULL);
                CREATE TABLE payroll_day_reviews (
                    pay_date text COLLATE "C" NOT NULL, person_id bigint NOT NULL REFERENCES people, review_key text COLLATE "C" NOT NULL,
                    decision text COLLATE "C" NOT NULL CHECK(decision IN ('include','exclude')), reviewed_by bigint NOT NULL REFERENCES people,
                    reviewed_at text COLLATE "C" NOT NULL, PRIMARY KEY(pay_date,person_id,review_key)
                );
                CREATE TABLE check_print_settings (
                    id integer PRIMARY KEY CHECK(id=1), x_tenths integer NOT NULL, y_tenths integer NOT NULL
                );
                CREATE TABLE entity_payroll_config (
                    entity_id bigint PRIMARY KEY REFERENCES entities, revision bigint NOT NULL CHECK(revision>0)
                );
                CREATE TABLE entity_payroll_rates (
                    entity_id bigint NOT NULL REFERENCES entity_payroll_config(entity_id) ON DELETE CASCADE,
                    position bigint NOT NULL, rate_key text COLLATE "C" NOT NULL, label text COLLATE "C" NOT NULL,
                    unit text COLLATE "C" NOT NULL, amount_10000 bigint NOT NULL CHECK(amount_10000 BETWEEN 0 AND 10000000000000),
                    PRIMARY KEY(entity_id,position), UNIQUE(entity_id,rate_key)
                );
                CREATE TABLE entity_payroll_formulas (
                    entity_id bigint NOT NULL REFERENCES entity_payroll_config(entity_id) ON DELETE CASCADE,
                    position bigint NOT NULL, label text COLLATE "C" NOT NULL,
                    basis text COLLATE "C" NOT NULL CHECK(basis IN ('daily','production')), expression text COLLATE "C" NOT NULL,
                    footage_credit text COLLATE "C" NOT NULL DEFAULT 'full' CHECK(footage_credit IN ('full','split')),
                    PRIMARY KEY(entity_id,position)
                );
                CREATE UNIQUE INDEX entity_payroll_formula_labels ON entity_payroll_formulas(entity_id,basis,lower(label));
                CREATE TABLE entity_rate_cards (
                    entity_id bigint PRIMARY KEY REFERENCES entities(id),
                    document text COLLATE "C" NOT NULL CHECK(document::json IS NOT NULL),
                    source_document text COLLATE "C" CHECK(source_document IS NULL OR source_document::json IS NOT NULL)
                );
                """);
        }
        FleetImport.initialize(db);
        MainlineSchema.initialize(db);
    }
}
