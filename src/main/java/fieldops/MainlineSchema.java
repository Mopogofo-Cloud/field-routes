package fieldops;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

final class MainlineSchema {
    private MainlineSchema() {}

    static final List<String> TABLES = List.of("mainline_projects", "mainline_dailies",
        "mainline_daily_members", "mainline_daily_vehicles", "mainline_media", "mainline_project_documents");

    private static List<String> statements(boolean pg) {
        String id = pg ? "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";
        String number = pg ? "bigint" : "INTEGER";
        var sql = new ArrayList<String>();
        sql.add("""
            CREATE TABLE IF NOT EXISTS mainline_projects (
              id %s, name TEXT NOT NULL, location TEXT NOT NULL DEFAULT '', supervisor TEXT NOT NULL DEFAULT '',
              state TEXT NOT NULL CHECK (state IN ('Not Started','In Progress','Completed')),
              lunch_provided INTEGER NOT NULL DEFAULT 0 CHECK (lunch_provided IN (0,1)),
              estimated_hundredths %s CHECK (estimated_hundredths>=0), driver_cents %s CHECK (driver_cents>=0),
              price_ten_thousandths %s CHECK (price_ten_thousandths>=0), due_date TEXT,
              revision %s NOT NULL DEFAULT 0)
            """.formatted(id,number,number,number,number));
        sql.add("""
            CREATE TABLE IF NOT EXISTS mainline_dailies (
              id %s, project_id %s NOT NULL REFERENCES mainline_projects(id), date TEXT NOT NULL,
              footage_hundredths %s NOT NULL DEFAULT 0 CHECK (footage_hundredths>=0),
              expenses TEXT NOT NULL DEFAULT '[]', priority TEXT CHECK (priority IN ('HIGH','MEDIUM','LOW')),
              comments TEXT NOT NULL DEFAULT '', revision %s NOT NULL DEFAULT 0)
            """.formatted(id,number,number,number));
        sql.add("CREATE INDEX IF NOT EXISTS mainline_dailies_by_project ON mainline_dailies(project_id,date,id)");
        sql.add("CREATE INDEX IF NOT EXISTS mainline_dailies_by_date ON mainline_dailies(date,id)");
        sql.add("""
            CREATE TABLE IF NOT EXISTS mainline_daily_members (
              daily_id %s NOT NULL REFERENCES mainline_dailies(id) ON DELETE CASCADE,
              person_id %s NOT NULL REFERENCES people(id), name TEXT NOT NULL,
              is_driver INTEGER NOT NULL DEFAULT 0 CHECK (is_driver IN (0,1)), PRIMARY KEY(daily_id,person_id))
            """.formatted(number,number));
        sql.add("CREATE INDEX IF NOT EXISTS mainline_member_dailies ON mainline_daily_members(person_id,daily_id)");
        sql.add("""
            CREATE TABLE IF NOT EXISTS mainline_daily_vehicles (
              daily_id %s NOT NULL REFERENCES mainline_dailies(id) ON DELETE CASCADE,
              vehicle_id %s NOT NULL REFERENCES vehicles(id), name TEXT NOT NULL, brand TEXT NOT NULL, plate TEXT NOT NULL,
              PRIMARY KEY(daily_id,vehicle_id))
            """.formatted(number,number));
        sql.add("CREATE INDEX IF NOT EXISTS mainline_vehicle_dailies ON mainline_daily_vehicles(vehicle_id,daily_id)");
        sql.addAll(MainlineMedia.schema(pg));
        sql.addAll(MainlineDocuments.schema(pg));
        return sql;
    }

    static void initialize(Connection db) throws SQLException {
        try (var stmt = db.createStatement()) {
            for (String definition : statements(StoreSql.postgres(db))) stmt.execute(definition);
        }
    }

    // Render the same definitions used by a fresh PostgreSQL installation for an existing private schema.
    public static void main(String[] args) {
        if (args.length != 1 || !"--print-migration".equals(args[0])) throw new IllegalArgumentException("Use --print-migration");
        System.out.println("BEGIN;\nSET LOCAL ROLE fieldroutes_owner;\nSET LOCAL search_path TO fieldroutes;\n");
        for (String definition : statements(true))
            System.out.println(definition.stripTrailing().replaceFirst(";$","") + ";\n");
        System.out.println("GRANT SELECT, INSERT, UPDATE, DELETE ON " + String.join(", ",TABLES) + " TO fieldroutes_app;");
        System.out.println("GRANT USAGE ON SEQUENCE mainline_projects_id_seq, mainline_dailies_id_seq, mainline_media_id_seq TO fieldroutes_app;");
        System.out.println("COMMIT;");
    }
}
